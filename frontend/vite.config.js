import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    // The frontend calls relative /api paths, and Vite forwards them to
    // FastAPI. That keeps the browser on one origin in development and means
    // no API key or backend URL ever ships to the client.
    proxy: {
      '/api': {
        target: process.env.VITE_BACKEND_URL || 'http://localhost:8000',
        changeOrigin: true,
      },
    },
  },
})
